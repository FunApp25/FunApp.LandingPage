/// Stable public hash-route names for legal and cookie-information pages.
abstract final class LegalRoutes {
  /// Approved Privacy Notice.
  static const privacy = '/privacy';

  /// Review-only Terms of Use document.
  static const terms = '/terms';

  /// Review-only Refund & Cancellation Policy document.
  static const refunds = '/refunds';

  /// Cookie information sourced from the approved Privacy Notice.
  static const cookies = '/cookies';

  /// Review-only, nonfunctional cookie-banner information.
  static const cookieBanner = '/cookie-banner';
}
