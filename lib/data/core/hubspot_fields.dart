  /// External property for the venue name.
  static const String venueName = 'your_venue_s_name';

  /// External property for the venue type.
  static const String venueType = 'type_of_venue';

  /// External property for independent or chain status.
  static const String chainStatus = 'independent_or_part_of_chain';

  /// External property for the number of venues in a chain.
  static const String venueCount = 'if_chain_number_of_venues';

  /// External property for venue capacity.
  static const String venueCapacity = 'your_venue_s_capacity';

  /// External property for the venue website.
  static const String website = 'website';

  /// External property for the contact's first name.
  static const String firstName = 'first_name';

  /// External property for the contact's last name.
  static const String lastName = 'last_name';

  /// External property for the contact's role.
  static const String role = 'role';

  /// External property for the contact's email address.
  static const String email = 'email';

  /// External property for the contact's phone number.
  static const String phoneNumber = 'phone_number';
}
